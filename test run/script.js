function showStartLight(text) {
  const lightEl = document.getElementById('start-light');
  if (!lightEl) return;
  lightEl.innerText = text;
  lightEl.style.display = 'block';
}

function hideStartLight() {
  const lightEl = document.getElementById('start-light');
  if (!lightEl) return;
  lightEl.style.display = 'none';
}

function showEndScreen(title, subtitle, color = '#00ff99') {
  const overlay = document.getElementById('end-screen');
  const msg = document.getElementById('end-message');
  const sub = document.getElementById('end-submessage');
  if (!overlay || !msg || !sub) return;

  msg.innerText = title;
  sub.innerText = subtitle;
  msg.style.color = color;
  overlay.style.display = 'flex';

  const btn = document.getElementById('restart-btn');
  if (btn) {
    // Remove any existing event listeners to prevent duplicates
    btn.onclick = null;
    // Add the restart functionality
    btn.onclick = function() {
      overlay.style.display = 'none';
      // Reset game state
      window.raceStarted = false;
      window.raceWon = false;
      // Reload the page to restart everything
      window.location.reload();
    };
  }
}

function startCountdown(duration = 3) {
  let counter = duration;
  showStartLight(counter);

  const intervalId = setInterval(() => {
    counter -= 1;
    if (counter > 0) {
      showStartLight(counter);
    } else if (counter === 0) {
      showStartLight('GO!');
    } else {
      clearInterval(intervalId);
      hideStartLight();
      window.raceStarted = true;
    }
  }, 1000);
}

